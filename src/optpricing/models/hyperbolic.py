from __future__ import annotations

from collections.abc import Callable
from typing import Any

import numpy as np
from scipy.special import kve
from scipy.stats import genhyperbolic

from optpricing.models.base import CF, BaseModel, ParamValidator, sample_from_cf

__doc__ = """
Defines the Hyperbolic pure-jump Levy model.
"""


class HyperbolicModel(BaseModel):
    """
    Hyperbolic Levy motion (Eberlein & Keller 1995).

    ``X_1`` follows the hyperbolic distribution (generalized hyperbolic with
    ``lambda = 1``) with parameters ``alpha, beta, delta, mu``; the process is the
    Levy process generated by that law, so ``phi_t(u) = phi_1(u)^t``. Note that
    ``X_t`` is *not* hyperbolic for ``t != 1`` (the class is not closed under
    convolution), hence terminal sampling for ``t != 1`` inverts the
    characteristic function numerically.
    """

    name: str = "Hyperbolic"
    supports_cf: bool = True
    is_pure_levy: bool = True
    default_params = {"alpha": 15.0, "beta": -5.0, "delta": 0.5, "mu": 0.0}

    def __init__(self, params: dict[str, float] | None = None):
        """
        Initializes the Hyperbolic model.

        Parameters
        ----------
        params : dict[str, float] | None, optional
            A dictionary of model parameters. If None, `default_params` are used.
            Defaults to None.
        """
        super().__init__(params or self.default_params)

    def _validate_params(self) -> None:
        p = self.params
        req = ["alpha", "beta", "delta", "mu"]
        ParamValidator.require(p, req, model=self.name)
        ParamValidator.positive(p, ["alpha", "delta"], model=self.name)
        if not (abs(p["beta"]) < p["alpha"]):
            raise ValueError("Hyperbolic params must satisfy |beta| < alpha.")
        if not (abs(p["beta"] + 1.0) < p["alpha"]):
            # E[exp(X_t)] is finite only if the exponential moment exists.
            raise ValueError(
                "Hyperbolic params must satisfy |beta + 1| < alpha for the "
                "risk-neutral measure to exist."
            )

    def __eq__(self, other: object) -> bool:
        if not isinstance(other, HyperbolicModel):
            return NotImplemented
        return self.params == other.params

    def __hash__(self) -> int:
        return hash((self.__class__, tuple(sorted(self.params.items()))))

    def _cf_impl(
        self,
        *,
        t: float,
        spot: float,
        r: float,
        q: float,
        **_: Any,
    ) -> CF:
        """
        Risk-neutral characteristic function for the log-spot price log(S_t).

        This is the risk-neutral characteristic function, which includes the
        drift adjustment.

        Parameters
        ----------
        t : float
            The time to maturity of the option, in years.
        spot : float
            The current price of the underlying asset.
        r : float
            The continuously compounded risk-free rate.
        q : float
            The continuously compounded dividend yield.

        Returns
        -------
        CF
            The characteristic function.
        """
        compensator = np.log(self.raw_cf(t=1.0)(-1j))  # E[exp(X_1)] = phi_raw(-i)
        drift = r - q - compensator

        def phi(u: np.ndarray | complex):
            return self.raw_cf(t=t)(u) * np.exp(1j * u * (np.log(spot) + drift * t))

        return phi

    def moment_strip(self) -> tuple[float, float]:
        """``|beta + s| < alpha`` (Eberlein & Keller 1995)."""
        alpha, beta = self.params["alpha"], self.params["beta"]
        return float(-alpha - beta), float(alpha - beta)

    def raw_cf(self, *, t: float) -> Callable:
        """
        Returns the CF of the raw Hyperbolic process, without drift or spot.

        This function represents the characteristic function of the process
        before the risk-neutral drift adjustment is applied.

        Parameters
        ----------
        t : float
            The time horizon.

        Returns
        -------
        Callable
            The raw characteristic function.
        """
        p = self.params
        alpha, beta, delta, mu = p["alpha"], p["beta"], p["delta"], p["mu"]
        gamma_0 = np.sqrt(alpha**2 - beta**2)
        log_k1_0 = np.log(kve(1, delta * gamma_0)) - delta * gamma_0

        def phi_raw(u: np.ndarray | complex) -> np.ndarray | complex:
            # Levy exponent psi_1(u) = log phi_1(u) of the hyperbolic law,
            # phi_1(u) = e^{iu mu} (g_0/g_u) K_1(delta g_u) / K_1(delta g_0).
            # log K_1 is evaluated as log(kve) - z so that the dominant, linearly
            # growing phase -delta*gamma_u never passes through a complex log
            # (branch-safe), which matters once it is multiplied by t.
            gamma_u = np.sqrt(alpha**2 - (beta + 1j * u) ** 2)
            z = delta * gamma_u
            psi = (
                1j * u * mu
                + np.log(gamma_0)
                - np.log(gamma_u)
                + np.log(kve(1, z))
                - z
                - log_k1_0
            )
            return np.exp(t * psi)

        return phi_raw

    def sample_terminal_log_return(
        self,
        T: float,
        size: int,
        rng: np.random.Generator,
    ) -> np.ndarray:
        """
        Generates samples of the terminal log-return of the raw process.

        For ``T == 1`` the law is the hyperbolic distribution itself and
        `scipy.stats.genhyperbolic` is sampled exactly (scipy's shape parameters
        are the dimensionless ``a = alpha*delta`` and ``b = beta*delta``). For any
        other horizon the terminal law has no closed form and is sampled by
        inverse transform of the characteristic function, see
        :func:`optpricing.models.base.sample_from_cf`.

        Parameters
        ----------
        T : float
            The time to maturity, in years.
        size : int
            The number of samples to generate.
        rng : np.random.Generator
            A random number generator instance for reproducibility.

        Returns
        -------
        np.ndarray
            An array of simulated terminal log-returns.
        """
        p = self.params
        if np.isclose(T, 1.0):
            return genhyperbolic.rvs(
                p=1.0,
                a=p["alpha"] * p["delta"],
                b=p["beta"] * p["delta"],
                loc=p["mu"],
                scale=p["delta"],
                size=size,
                random_state=rng,
            )
        return sample_from_cf(self.raw_cf(t=T), size, rng)

    #  Abstract Method Implementations
    def _sde_impl(self, **kwargs: Any) -> Any:
        raise NotImplementedError

    def _pde_impl(self, **kwargs: Any) -> Any:
        raise NotImplementedError

    def _closed_form_impl(self, **kwargs: Any) -> Any:
        raise NotImplementedError
